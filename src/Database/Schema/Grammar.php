<?php

declare(strict_types=1);

namespace Racin\Database\Schema;

use LogicException;
use Racin\Database\Connection;
use Racin\Database\Expression;

/**
 * Compiles blueprints to DDL for MySQL/MariaDB, SQLite and PostgreSQL.
 */
final class Grammar
{
    public function __construct(private readonly Connection $connection)
    {
    }

    /**
     * @return list<string>
     */
    public function compileCreate(Blueprint $blueprint): array
    {
        $driver = $this->connection->driver();
        $lines = array_map($this->columnDefinition(...), $blueprint->columns);
        $after = [];

        if ($blueprint->primaryKey !== null && $driver === 'mysql') {
            $lines[] = 'PRIMARY KEY (' . $this->wrap($blueprint->primaryKey) . ')';
        }

        foreach ($blueprint->indexes as $index) {
            if ($index['type'] === 'primary') {
                $lines[] = 'PRIMARY KEY (' . $this->columnList($index['columns']) . ')';
            } elseif ($driver === 'mysql') {
                $lines[] = ($index['type'] === 'unique' ? 'UNIQUE KEY ' : 'KEY ') . $this->wrap($index['name']) . ' (' . $this->columnList($index['columns']) . ')';
            } else {
                $after[] = $this->createIndex($blueprint->table, $index);
            }
        }

        foreach ($blueprint->foreignKeys as $foreign) {
            $lines[] = $this->foreignKey($foreign);
        }

        foreach ($blueprint->checks as $check) {
            $lines[] = 'CONSTRAINT ' . $this->wrap($check['name']) . ' CHECK (' . $check['sql'] . ')';
        }

        $sql = 'CREATE TABLE ' . $this->connection->wrapTable($blueprint->table) . " (\n    " . implode(",\n    ", $lines) . "\n)";

        if ($driver === 'mysql') {
            $sql .= ' ENGINE = InnoDB DEFAULT CHARSET = ' . $this->safe((string) ($this->config('charset') ?? 'utf8mb4'))
                . ' COLLATE = ' . $this->safe((string) ($this->config('collation') ?? 'utf8mb4_unicode_ci'));
        }

        return [$sql, ...$after];
    }

    /**
     * @return list<string>
     */
    public function compileAlter(Blueprint $blueprint): array
    {
        $driver = $this->connection->driver();
        $table = $this->connection->wrapTable($blueprint->table);
        $statements = [];

        foreach ($blueprint->columns as $column) {
            $statements[] = "ALTER TABLE {$table} ADD COLUMN " . $this->columnDefinition($column);
        }

        foreach ($blueprint->indexes as $index) {
            if ($index['type'] === 'primary') {
                throw new LogicException('Adding a primary key to an existing table is not supported.');
            }

            $statements[] = $driver === 'mysql'
                ? "ALTER TABLE {$table} ADD " . ($index['type'] === 'unique' ? 'UNIQUE ' : '') . 'INDEX ' . $this->wrap($index['name']) . ' (' . $this->columnList($index['columns']) . ')'
                : $this->createIndex($blueprint->table, $index);
        }

        foreach ($blueprint->foreignKeys as $foreign) {
            if ($driver === 'sqlite') {
                throw new LogicException('SQLite cannot add foreign keys to an existing table; define them in create().');
            }

            $statements[] = "ALTER TABLE {$table} ADD " . $this->foreignKey($foreign);
        }

        foreach ($blueprint->dropIndexes as $name) {
            $statements[] = $driver === 'mysql'
                ? "ALTER TABLE {$table} DROP INDEX " . $this->wrap($name)
                : 'DROP INDEX ' . $this->wrap($name);
        }

        foreach ($blueprint->dropColumns as $column) {
            $statements[] = "ALTER TABLE {$table} DROP COLUMN " . $this->wrap($column);
        }

        return $statements;
    }

    private function columnDefinition(ColumnDefinition $column): string
    {
        $driver = $this->connection->driver();
        $name = $this->wrap($column->name);

        if ($column->autoIncrement) {
            return match ($driver) {
                'sqlite' => "{$name} INTEGER PRIMARY KEY AUTOINCREMENT",
                'pgsql' => "{$name} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                default => "{$name} BIGINT UNSIGNED NOT NULL AUTO_INCREMENT",
            };
        }

        $sql = $name . ' ' . $this->type($column);

        if ($column->unsigned && $driver === 'mysql') {
            $sql .= ' UNSIGNED';
        }

        $sql .= $column->nullable ? ' NULL' : ' NOT NULL';

        if ($column->hasDefault) {
            $sql .= ' DEFAULT ' . $this->defaultValue($column->default);
        }

        if ($column->type === 'enum' && $driver !== 'mysql') {
            $values = implode(', ', array_map($this->connection->quoteString(...), $column->parameters['values']));
            $sql .= " CHECK ({$name} IN ({$values}))";
        }

        return $sql;
    }

    private function type(ColumnDefinition $column): string
    {
        $driver = $this->connection->driver();
        $p = $column->parameters;

        return match ($column->type) {
            'string' => 'VARCHAR(' . (int) $p['length'] . ')',
            'char' => 'CHAR(' . (int) $p['length'] . ')',
            'text' => 'TEXT',
            'longText' => $driver === 'mysql' ? 'LONGTEXT' : 'TEXT',
            'integer' => $driver === 'mysql' ? 'INT' : 'INTEGER',
            'bigInteger' => $driver === 'sqlite' ? 'INTEGER' : 'BIGINT',
            'smallInteger' => $driver === 'sqlite' ? 'INTEGER' : 'SMALLINT',
            'tinyInteger' => match ($driver) {
                'mysql' => 'TINYINT',
                'pgsql' => 'SMALLINT',
                default => 'INTEGER',
            },
            'boolean' => match ($driver) {
                'mysql' => 'TINYINT(1)',
                'pgsql' => 'SMALLINT',
                default => 'INTEGER',
            },
            'decimal' => ($driver === 'pgsql' ? 'NUMERIC' : 'DECIMAL') . '(' . (int) $p['precision'] . ', ' . (int) $p['scale'] . ')',
            'double' => match ($driver) {
                'pgsql' => 'DOUBLE PRECISION',
                'sqlite' => 'REAL',
                default => 'DOUBLE',
            },
            'date' => 'DATE',
            'dateTime' => match ($driver) {
                'pgsql' => 'TIMESTAMP(0) WITHOUT TIME ZONE',
                default => 'DATETIME',
            },
            'json' => match ($driver) {
                'pgsql' => 'JSONB',
                'sqlite' => 'TEXT',
                default => 'JSON',
            },
            'enum' => $driver === 'mysql'
                ? 'ENUM(' . implode(', ', array_map($this->connection->quoteString(...), $p['values'])) . ')'
                : 'VARCHAR(255)',
            default => throw new LogicException("Unknown column type [{$column->type}]."),
        };
    }

    private function defaultValue(mixed $value): string
    {
        return match (true) {
            $value === null => 'NULL',
            $value instanceof Expression => $value->value,
            is_bool($value) => $value ? '1' : '0',
            is_int($value), is_float($value) => (string) $value,
            default => $this->connection->quoteString((string) $value),
        };
    }

    /**
     * @param array{type: string, columns: list<string>, name: string} $index
     */
    private function createIndex(string $table, array $index): string
    {
        return 'CREATE ' . ($index['type'] === 'unique' ? 'UNIQUE ' : '') . 'INDEX ' . $this->wrap($index['name'])
            . ' ON ' . $this->connection->wrapTable($table) . ' (' . $this->columnList($index['columns']) . ')';
    }

    private function foreignKey(ForeignKeyDefinition $foreign): string
    {
        if ($foreign->onTable === '') {
            throw new LogicException("Foreign key on [{$foreign->column}] needs ->on('table').");
        }

        return 'CONSTRAINT ' . $this->wrap($foreign->name)
            . ' FOREIGN KEY (' . $this->wrap($foreign->column) . ')'
            . ' REFERENCES ' . $this->connection->wrapTable($foreign->onTable) . ' (' . $this->wrap($foreign->referencesColumn) . ')'
            . ' ON DELETE ' . strtoupper($foreign->onDelete)
            . ' ON UPDATE ' . strtoupper($foreign->onUpdate);
    }

    /**
     * @param list<string> $columns
     */
    private function columnList(array $columns): string
    {
        return implode(', ', array_map($this->wrap(...), $columns));
    }

    private function wrap(string $identifier): string
    {
        return $this->connection->wrap($identifier);
    }

    private function config(string $key): mixed
    {
        return $this->connection->getConfig($key);
    }

    private function safe(string $name): string
    {
        if (preg_match('/^[A-Za-z0-9_]+$/', $name) !== 1) {
            throw new LogicException("Invalid charset/collation [{$name}].");
        }

        return $name;
    }
}
