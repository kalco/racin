<?php

declare(strict_types=1);

namespace Racin\Tests;

use PHPUnit\Framework\TestCase;
use Racin\Database\Connection;
use Racin\Database\DatabaseManager;
use Racin\Database\Migrations\Migrator;
use Racin\Database\QueryException;
use Racin\Database\Schema\Blueprint;

final class SchemaTest extends TestCase
{
    private static function posts(Blueprint $table): void
    {
        $table->id();
        $table->foreignId('user_id')->constrained()->cascadeOnDelete();
        $table->string('title', 200);
        $table->text('body')->nullable();
        $table->boolean('published')->default(false)->index();
        $table->decimal('price', 8, 2)->default(0);
        $table->enum('state', ['draft', 'live'])->default('draft');
        $table->json('meta')->nullable();
        $table->timestamps();
        $table->unique(['user_id', 'title']);
    }

    public function testMysqlDdl(): void
    {
        $sql = (new Connection(['driver' => 'mysql', 'charset' => 'utf8mb4', 'collation' => 'utf8mb4_unicode_ci']))->schema()->toSql('posts', self::posts(...));

        self::assertCount(1, $sql, 'MySQL defines indexes inline');
        self::assertStringContainsString('`id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT', $sql[0]);
        self::assertStringContainsString('`published` TINYINT(1) NOT NULL DEFAULT 0', $sql[0]);
        self::assertStringContainsString("`state` ENUM('draft', 'live') NOT NULL DEFAULT 'draft'", $sql[0]);
        self::assertStringContainsString('UNIQUE KEY `posts_user_id_title_unique` (`user_id`, `title`)', $sql[0]);
        self::assertStringContainsString('CONSTRAINT `posts_user_id_foreign` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE', $sql[0]);
        self::assertStringEndsWith('ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci', $sql[0]);
    }

    public function testPostgresDdl(): void
    {
        $sql = (new Connection(['driver' => 'pgsql']))->schema()->toSql('posts', self::posts(...));

        self::assertStringContainsString('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql[0]);
        self::assertStringContainsString('"published" SMALLINT NOT NULL DEFAULT 0', $sql[0]);
        self::assertStringContainsString('"price" NUMERIC(8, 2) NOT NULL DEFAULT 0', $sql[0]);
        self::assertStringContainsString("\"state\" VARCHAR(255) NOT NULL DEFAULT 'draft' CHECK (\"state\" IN ('draft', 'live'))", $sql[0]);
        self::assertStringContainsString('"meta" JSONB NULL', $sql[0]);
        self::assertStringContainsString('"created_at" TIMESTAMP(0) WITHOUT TIME ZONE NULL', $sql[0]);
        self::assertSame([
            'CREATE INDEX "posts_published_index" ON "posts" ("published")',
            'CREATE UNIQUE INDEX "posts_user_id_title_unique" ON "posts" ("user_id", "title")',
        ], array_slice($sql, 1));
    }

    public function testSqliteCreateAlterAndIntrospection(): void
    {
        $schema = (new Connection(['driver' => 'sqlite', 'database' => ':memory:']))->schema();
        $schema->create('users', function (Blueprint $table): void {
            $table->id();
            $table->string('email')->unique();
        });
        $schema->create('posts', self::posts(...));

        self::assertTrue($schema->hasTable('posts'));
        self::assertTrue($schema->hasColumn('posts', 'meta'));
        self::assertSame(['posts', 'users'], $schema->getTables());

        $schema->table('posts', function (Blueprint $table): void {
            $table->integer('views')->default(0);
            $table->index('views');
        });
        self::assertTrue($schema->hasColumn('posts', 'views'));

        $schema->table('posts', fn (Blueprint $table) => $table->dropColumn('views'));
        self::assertFalse($schema->hasColumn('posts', 'views'));

        $connection = $schema->connection();
        $connection->table('users')->insert(['email' => 'a@x.io']);
        $connection->table('posts')->insert(['user_id' => 1, 'title' => 'Hi']);
        $row = $connection->table('posts')->first();
        self::assertSame(['published' => 0, 'price' => 0, 'state' => 'draft'], ['published' => $row['published'], 'price' => $row['price'], 'state' => $row['state']]);

        try {
            $connection->table('posts')->insert(['user_id' => 1, 'title' => 'Bad', 'state' => 'nope']);
            self::fail('enum CHECK should reject');
        } catch (QueryException) {
        }

        $schema->dropAllTables();
        self::assertSame([], $schema->getTables());
    }

    public function testMigratorRunsRollsBackAndReportsStatus(): void
    {
        $dir = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'racin-migrations-' . bin2hex(random_bytes(4));
        mkdir($dir);

        $migration = static fn (string $table): string => <<<PHP
            <?php
            use Racin\\Database\\Migrations\\Migration;
            use Racin\\Database\\Schema\\Blueprint;
            use Racin\\Database\\Schema\\Schema;
            return new class extends Migration {
                public function up(Schema \$schema): void { \$schema->create('{$table}', fn (Blueprint \$t) => \$t->id()); }
                public function down(Schema \$schema): void { \$schema->dropIfExists('{$table}'); }
            };
            PHP;

        file_put_contents("{$dir}/2026_01_01_000001_a.php", $migration('alpha'));
        file_put_contents("{$dir}/2026_01_01_000002_b.php", $migration('beta'));

        $db = new DatabaseManager(['default' => 'sqlite', 'connections' => ['sqlite' => ['driver' => 'sqlite', 'database' => ':memory:']]]);
        $migrator = new Migrator($db, $dir);

        try {
            self::assertSame(['2026_01_01_000001_a', '2026_01_01_000002_b'], $migrator->migrate());
            self::assertSame([], $migrator->migrate(), 'nothing pending');

            file_put_contents("{$dir}/2026_01_01_000003_c.php", $migration('gamma'));
            self::assertSame(['2026_01_01_000003_c'], $migrator->migrate());
            self::assertSame([1, 1, 2], array_column($migrator->status(), 'batch'));

            self::assertSame(['2026_01_01_000003_c'], $migrator->rollback());
            self::assertFalse($db->connection()->schema()->hasTable('gamma'));
            self::assertTrue($db->connection()->schema()->hasTable('beta'));

            file_put_contents("{$dir}/2026_01_01_000004_broken.php", "<?php\nuse Racin\\Database\\Migrations\\Migration;\nuse Racin\\Database\\Schema\\Schema;\nreturn new class extends Migration { public function up(Schema \$schema): void { \$schema->connection()->statement('CREATE TABLE delta (id INT)'); throw new RuntimeException('boom'); } };");

            try {
                $migrator->migrate();
                self::fail('Expected failure');
            } catch (\RuntimeException $e) {
                self::assertStringContainsString('2026_01_01_000004_broken', $e->getMessage());
            }

            self::assertFalse($db->connection()->schema()->hasTable('delta'), 'SQLite rolled the failed migration back');
            // "c" (rolled back earlier) ran again before "broken" failed.
            self::assertSame(['2026_01_01_000004_broken'], array_column(array_filter($migrator->status(), fn ($r) => !$r['ran']), 'migration'));
        } finally {
            array_map('unlink', glob("{$dir}/*.php") ?: []);
            rmdir($dir);
        }
    }

    public function testPostgresQueryCompilation(): void
    {
        $pg = new Connection(['driver' => 'pgsql']);

        self::assertSame(
            'SELECT * FROM "products" WHERE "name" ILIKE ? OFFSET 20 FOR UPDATE SKIP LOCKED',
            $pg->table('products')->where('name', 'ilike', '%a%')->offset(20)->lockForUpdate()->skipLocked()->toSql(),
        );
        self::assertSame(
            'SELECT * FROM `products` WHERE `name` LIKE ? LOCK IN SHARE MODE',
            (new Connection(['driver' => 'mysql']))->table('products')->where('name', 'ilike', '%a%')->sharedLock()->toSql(),
        );
    }
}
